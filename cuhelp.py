"""What each coreutils program prints for --help, as the guest prints it.

Measured 2026-09-03 against the guest's own coreutils 9.7. Of the 102 names
our coreutils claims, exactly one answered --help the way the guest does.
Forty-five printed nothing at all -- cat, head, sort, stat and readlink
among them -- and the rest ran with --help taken as an operand, which is
how `arch --help` came to answer "x86_64" and `basename --help` to answer
"--help".

--help is what someone types when a command did not do what they expected.
A box that runs the command instead answers a question nobody asked, at
the moment it is being examined.

Six names are absent on purpose: echo, false, printf, pwd, test and true
are bash builtins here, and the builtin shadows the binary -- `echo
--help` in a shell prints "--help", not coreutils' help. Taking the text
from this table for those would be a new mistake in place of the old one.
chroot is absent because the guest does not have it on PATH to measure.

Collected with the BARE command name, not a resolved path. The first
attempt ran `$(command -v cat) --help`, and coreutils prints its own
argv[0]: every usage line came back as "Usage: /usr/bin/cat [OPTION]..."
and would have shipped a tell worse than the empty output it replaced. It
was caught by a 27-byte disagreement between two measurements of the same
command. The paths that remain -- in basename's and dirname's help -- are
examples inside the real text.

Kept beside fakeshell.py rather than inside it, the way localedb.py and
tzdb.py are: it is measured data, not logic.
"""

